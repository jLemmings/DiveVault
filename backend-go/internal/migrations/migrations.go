func migrationV2(ctx context.Context, tx pgx.Tx) error {
	_, err := tx.Exec(ctx, `
        UPDATE dives
        SET fields_json = jsonb_set(COALESCE(fields_json, '{}'::jsonb), '{tanks}', '[{"volume": 12.0}]'::jsonb, true)
        WHERE NOT (COALESCE(fields_json, '{}'::jsonb) #> '{tanks,0}' ? 'volume')
    `)
	return err
}

func migrationV7(ctx context.Context, tx pgx.Tx) error {
	if _, err := tx.Exec(ctx, migrationV7SQL); err != nil {
		return err
	}
	var ownerUserID *string
	err := tx.QueryRow(ctx, "SELECT id FROM auth_users ORDER BY created_at ASC, email ASC LIMIT 1").Scan(&ownerUserID)
	if err != nil && !errors.Is(err, pgx.ErrNoRows) {
		return err
	}
	if errors.Is(err, pgx.ErrNoRows) {
		return nil
	}
	if ownerUserID != nil && *ownerUserID != "" {
		_, err = tx.Exec(ctx, `
            UPDATE auth_instance_settings
            SET initialized=TRUE, owner_user_id=COALESCE(owner_user_id, $1), updated_at=$2
            WHERE singleton=TRUE
        `, *ownerUserID, nowISO())
	}
	return err
}

func nowISO() string {
	return time.Now().UTC().Format(time.RFC3339Nano)
}

