const schemaVersionSQL = `
CREATE TABLE IF NOT EXISTS app_schema_version (
    singleton BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (singleton),
    version INTEGER NOT NULL,
    updated_at TEXT NOT NULL
);
`

type migration struct {
	version int
	sql     string
	fn      func(context.Context, pgx.Tx) error
}

func Migrate(ctx context.Context, db *store.DB) (int, error) {
	if db == nil || db.Pool() == nil {
		return 0, errors.New("database is not configured")
	}
	tx, err := db.Pool().Begin(ctx)
	if err != nil {
		return 0, err
	}
	defer tx.Rollback(ctx)

	if _, err := tx.Exec(ctx, schemaSQL); err != nil {
		return 0, err
	}
	version, err := schemaVersion(ctx, tx)
	if err != nil {
		return 0, err
	}
	for _, migration := range migrations() {
		if version >= migration.version {
			continue
		}
		if migration.sql != "" {
			if _, err := tx.Exec(ctx, migration.sql); err != nil {
				return version, fmt.Errorf("apply migration v%d: %w", migration.version, err)
			}
		}
		if migration.fn != nil {
			if err := migration.fn(ctx, tx); err != nil {
				return version, fmt.Errorf("apply migration v%d: %w", migration.version, err)
			}
		}
		if err := setSchemaVersion(ctx, tx, migration.version); err != nil {
			return version, err
		}
		version = migration.version
	}
	if err := tx.Commit(ctx); err != nil {
		return version, err
	}
	return version, nil
}

func SchemaVersion(ctx context.Context, db *store.DB) (int, error) {
	if db == nil || db.Pool() == nil {
		return 0, errors.New("database is not configured")
	}
	tx, err := db.Pool().Begin(ctx)
	if err != nil {
		return 0, err
	}
	defer tx.Rollback(ctx)
	version, err := schemaVersion(ctx, tx)
	if err != nil {
		return 0, err
	}
	return version, tx.Commit(ctx)
}

func schemaVersion(ctx context.Context, tx pgx.Tx) (int, error) {
	if _, err := tx.Exec(ctx, schemaVersionSQL); err != nil {
		return 0, err
	}
	if _, err := tx.Exec(ctx, `
        INSERT INTO app_schema_version(singleton, version, updated_at)
        VALUES (TRUE, 0, $1)
        ON CONFLICT (singleton) DO NOTHING
    `, nowISO()); err != nil {
		return 0, err
	}
	var version int
	if err := tx.QueryRow(ctx, "SELECT version FROM app_schema_version WHERE singleton=TRUE").Scan(&version); err != nil {
		return 0, err
	}
	return version, nil
}

func setSchemaVersion(ctx context.Context, tx pgx.Tx, version int) error {
	_, err := tx.Exec(ctx, "UPDATE app_schema_version SET version=$1, updated_at=$2 WHERE singleton=TRUE", version, nowISO())
	return err
}

